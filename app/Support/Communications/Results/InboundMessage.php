<?php

declare(strict_types=1);

namespace App\Support\Communications\Results;

use App\Support\Communications\Channel;
use App\Support\Communications\MessageDirection;
use Carbon\CarbonImmutable;

/**
 * Normalised inbound content from a provider webhook.
 *
 * @phpstan-type HeaderMap array<string, string>
 */
final readonly class InboundMessage
{
    /**
     * @param  HeaderMap  $headers
     * @param  list<InboundAttachment>  $attachments
     * @param  array<string, mixed>  $raw
     * @param  array<string, mixed>|null  $sourceRef
     */
    public function __construct(
        public string $providerMessageId,
        public string $providerEventId,
        public Channel $channel,
        public string $from,
        public string $to,
        public ?string $subject,
        public ?string $bodyText,
        public ?string $bodyHtml,
        public array $headers,
        public array $attachments,
        public bool $autoGenerated,
        public ?CarbonImmutable $occurredAt,
        public array $raw,
        public MessageDirection $direction = MessageDirection::Inbound,
        public ?array $sourceRef = null,
        public ?bool $countsAsUnread = null,
    ) {}

    public function shouldCountAsUnread(): bool
    {
        return $this->countsAsUnread ?? ! $this->autoGenerated;
    }

    /**
     * Counterparty address used for contact match + SMS/call threading.
     * Call outbound uses `to` (external party); everything else uses `from`.
     */
    public function counterparty(): string
    {
        if ($this->channel === Channel::Call && $this->direction === MessageDirection::Outbound) {
            return $this->to;
        }

        return $this->from;
    }
}
